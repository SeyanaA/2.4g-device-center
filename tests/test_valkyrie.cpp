#include "proto_valkyrie.h"

#include <cassert>
#include <cstring>
#include <iostream>

namespace {

void TestReceiverCapture() {
    const uint8_t payload[32] = {
        0x10, 0x00, 0x01, 0x0B, 0x4D, 0x32, 0x32, 0x30, 0x84, 0x01, 0x11,
        0x01, 0x00, 0x4E, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xC7,
    };
    ValkyrieIdentity id;
    assert(ParseValkyrieIdentity(payload, sizeof(payload), id));
    assert(id.modelCode == "M220");
    assert(id.firmware == 0x0184);
    assert(id.sensor == 0x11);
    assert(id.sensorVariant == 1);
    assert(id.batteryStatus == 0);
    assert(id.batteryPercent == 78);
    assert(id.connectionStatus == 1);
}

void TestWiredCapture() {
    const uint8_t payload[32] = {
        0x10, 0x00, 0x01, 0x0B, 0x4D, 0x32, 0x32, 0x30, 0x17, 0x03, 0x11,
        0x01, 0x01, 0x64, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x73,
    };
    ValkyrieIdentity id;
    assert(ParseValkyrieIdentity(payload, sizeof(payload), id));
    assert(id.modelCode == "M220");
    assert(id.firmware == 0x0317);
    assert(id.batteryStatus == 1);
    assert(id.batteryPercent == 100);
}

void TestLiveReceiverCapture() {
    const uint8_t payload[32] = {
        0x10, 0x00, 0x01, 0x0B, 0x4D, 0x32, 0x32, 0x30, 0x84, 0x01, 0x11,
        0x01, 0x00, 0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xB9,
    };
    ValkyrieIdentity id;
    assert(ParseValkyrieIdentity(payload, sizeof(payload), id));
    assert(id.batteryPercent == 65);
    assert(id.batteryStatus == 0);
    assert(id.connectionStatus == 0);
}

void TestBadChecksumRejected() {
    uint8_t payload[32] = {
        0x10, 0x00, 0x01, 0x0B, 0x4D, 0x32, 0x32, 0x30, 0x84, 0x01, 0x11,
        0x01, 0x00, 0x4E, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xC7,
    };
    payload[31] ^= 0x01;
    ValkyrieIdentity id;
    assert(!ParseValkyrieIdentity(payload, sizeof(payload), id));
}

void TestBadHeaderRejected() {
    uint8_t payload[32] = {
        0x11, 0x00, 0x01, 0x0B, 0x4D, 0x32, 0x32, 0x30, 0x84, 0x01, 0x11,
        0x01, 0x00, 0x4E, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xC7,
    };
    ValkyrieIdentity id;
    assert(!ParseValkyrieIdentity(payload, sizeof(payload), id));
}

void TestBatteryRangeRejected() {
    uint8_t payload[32] = {
        0x10, 0x00, 0x01, 0x0B, 0x4D, 0x32, 0x32, 0x30, 0x84, 0x01, 0x11,
        0x01, 0x00, 0x65, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    };
    uint8_t sum = 0;
    for (int i = 4; i <= 30; ++i) sum += payload[i];
    payload[31] = sum;
    ValkyrieIdentity id;
    assert(!ParseValkyrieIdentity(payload, sizeof(payload), id));
}

}  // namespace

int main() {
    TestReceiverCapture();
    TestWiredCapture();
    TestLiveReceiverCapture();
    TestBadChecksumRejected();
    TestBadHeaderRejected();
    TestBatteryRangeRejected();
    assert(ValkyrieModelName("M220") == L"Valkyrie VK M3 Lite");
    assert(ValkyrieModelName("E023") == L"Valkyrie VK M3");
    assert(ValkyrieModelName("XXXX").empty());
    std::cout << "valkyrie: 9 tests passed\n";
    return 0;
}
